/**
 * 규칙 기반 로컬 요약기.
 *
 * PRD §8 — AI는 선택적이고 보조적이다. 쓰지 않아도 서비스가 온전히 동작해야 하며,
 * 실패·지연 시 사용자는 항상 직접 입력으로 우회할 수 있다.
 * 서버(AI)가 없거나 실패하면 이 함수가 그 자리를 메운다.
 */
export function localSummarize(raw: string): string {
  let t = (raw || '').trim().replace(/\s+/g, ' ');
  t = t
    .replace(/(그니까|그러니까|일단|약간|아무튼|뭐지|이런 얘기죠|이런 거죠|음+|^아 |어+ )/g, '')
    .trim();
  if (t.length > 46) {
    const parts = t
      .split(/[.?!·]|\s그리고\s|,\s?/)
      .map((x) => x.trim())
      .filter((x) => x.length > 3);
    if (parts.length) t = parts.sort((a, b) => b.length - a.length)[0];
  }
  const map: [RegExp, string][] = [
    [/하자$/, '한다'], [/보자$/, '본다'], [/가자$/, '간다'], [/미루자$/, '미룬다'],
    [/줄이자$/, '줄인다'], [/늘리자$/, '늘린다'], [/빼자$/, '뺀다'], [/넣자$/, '넣는다'],
    [/내자$/, '낸다'], [/리자$/, '린다'], [/이자$/, '인다'], [/쓰자$/, '쓴다'],
    [/받자$/, '받는다'], [/막자$/, '막는다'], [/잡자$/, '잡는다'], [/자$/, '기로 함'],
    [/것 같은데$/, '것으로 보임'], [/같은데$/, '것으로 보임'], [/(는데|은데)$/, '음'],
    [/해야죠$/, '해야 함'], [/(해요|합니다)$/, '한다'], [/(인데|이지만)$/, '임'],
    [/필요할듯$/, '필요함'], [/(듯|듯요)$/, '것으로 보임'], [/(요|네요|죠)$/, '']
  ];
  for (const [re, rep] of map) {
    if (re.test(t)) {
      t = t.replace(re, rep);
      break;
    }
  }
  if (t.length > 46) t = t.slice(0, 44) + '…';
  return t || raw;
}
